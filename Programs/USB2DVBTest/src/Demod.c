BOOL
AF9015_DemodInit( struct Receiver *receiver )
{
	static const U8 api[] = { 0, 1, 9, 0 };
	static const struct RegisterSetting wake[] =
	{
		{ 0xd735, 0xff, 0x07 },
		{ 0xd736, 0xff, 0x30 },
		{ 0xd73a, 0x08, 0x00 },
		{ 0xd417, 0x02, 0x00 },
		{ 0xd417, 0x10, 0x00 }
	};
	static const struct RegisterSetting output[] =
	{
		{ 0xd500, 0x0e, 0x00 }, // Route the transport stream to USB.
		{ 0xd730, 0x01, 0x01 },
		{ 0xd503, 0x01, 0x00 }  // Disable PID filtering for multiplex capture.
	};

	const struct RegisterSetting *table;

	U32 count;
	U32 adc;
	U8 clock[3];

	switch( receiver->Tuner )
	{
		case AF9015_MT2060:
			table = MT2060Settings;
			count = COUNT( MT2060Settings );
			break;
		case AF9015_MT2060_2:
			table = MT2060AltSettings;
			count = COUNT( MT2060AltSettings );
			break;
		case AF9015_TDA18218:
			table = TDA18218Settings;
			count = COUNT( TDA18218Settings );
			break;
		default:
			Printf( "AF9015 tuner ID $%02lx is unsupported for tuning.\n", (U32) receiver->Tuner );

			return ( FALSE );
	}

	adc = (U64) receiver->Clock * 0x80000 / 1000000;
	clock[0] = adc;
	clock[1] = adc >> 8;
	clock[2] = adc >> 16;
	receiver->DemodAwake = TRUE;

	return ( ( AF9015_Table( receiver, wake, COUNT( wake ) ) ) &&
		( AF9015_Write( receiver, 0x9bf2, api, sizeof( api ) ) ) &&
		( AF9015_Set( receiver, 0x9bd2, 0x0f, receiver->ClockType ) ) &&
		( AF9015_Write( receiver, 0xd180, clock, sizeof( clock ) ) ) &&
		( AF9015_Table( receiver, DemodSettings, COUNT( DemodSettings ) ) ) &&
		( AF9015_Table( receiver, table, count ) ) &&
		( AF9015_Table( receiver, output, COUNT( output ) ) ) );
}

