BOOL
AF9015_DemodTune( struct Receiver *receiver, U32 bandwidth )
{
	static const struct RegisterSetting clearLock[] =
	{
		{ 0xd330, 0x08, 0x08 },
		{ 0xd507, 0x40, 0x00 },
		{ 0x9bfe, 0x01, 0x00 },
		{ 0x9bc2, 0x01, 0x00 }
	};

	const struct Coefficients *coeff;

	S32 sample;
	U32 index;
	U32 frequency;
	U8 control[6];
	U8 params[3];

	coeff = NULL;

	for( index = 0; index < COUNT( Coefficients ); index++ )
	{
		if ( ( Coefficients[index].Clock == receiver->Clock ) && ( Coefficients[index].Bandwidth == bandwidth ) )
		{
			coeff = & Coefficients[index];

			break;
		}
	}

	if ( ! coeff )
	{
		return ( FALSE );
	}

	// The supported tuners invert the spectrum. Fold IF into the ADC passband.
	sample = receiver->IFrequency;

	while( sample > (S32) ( receiver->Clock / 2 ) )
	{
		sample -= (S32) receiver->Clock;
	}

	frequency = ( (U64) ( sample < 0 ? -sample : sample ) * 0x800000 + receiver->Clock / 2 ) / receiver->Clock;

	if ( sample < 0 )
	{
		frequency = 0x800000 - frequency;
	}

	control[0] = frequency;
	control[1] = frequency >> 8;
	control[2] = ( frequency >> 16 ) & 0x7f;
	frequency = 0x800000 - frequency;
	control[3] = frequency;
	control[4] = frequency >> 8;
	control[5] = ( frequency >> 16 ) & 0x7f;

	params[0] = 0;
	params[1] = ( bandwidth / 1000000 - 6 ) << 2;
	params[2] = 0;

	return ( ( AF9015_Write( receiver, 0xae00, coeff->Values, sizeof( coeff->Values ) ) ) &&
		( AF9015_Write( receiver, 0xd140, control, 3 ) ) &&
		( AF9015_Write( receiver, 0x9be7, control, sizeof( control ) ) ) &&
		( AF9015_Table( receiver, clearLock, COUNT( clearLock ) ) ) &&
		( AF9015_Write( receiver, 0xd3c0, params, sizeof( params ) ) ) &&
		( AF9015_Set( receiver, 0xaefd, 0xff, 0 ) ) &&
		( AF9015_Set( receiver, 0xffff, 0xff, 0 ) ) );
}

