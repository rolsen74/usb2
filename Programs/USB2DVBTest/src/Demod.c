void
AF9015_DemodSleep( struct Receiver *receiver )
{
	U32 attempt;
	U8 status;

	if ( ( ! AF9015_Set( receiver, 0xd730, 0x01, 0 ) ) ||
		( ! AF9015_Set( receiver, 0xd417, 0x10, 0x10 ) ) ||
		( ! AF9015_Set( receiver, 0xaeff, 0xff, 1 ) ) )
	{
		return;
	}

	for( attempt = 0; attempt < 50; attempt++ )
	{
		if ( ! AF9015_Read( receiver, 0xd417, & status, 1 ) )
		{
			return;
		}

		if ( status & 0x02 )
		{
			AF9015_Set( receiver, 0xd73a, 0x08, 0x08 );

			return;
		}

		Delay( 1 );
	}
}

