S32
RTL8188EU_InitRF( struct USB2_EPResource *control )
{
	U32 index;

	for( index = 0; index < sizeof( registers ) / sizeof( registers[0] ); index++ )
	{
		// The vendor RF table uses pseudo-addresses to request settling delays.
		if ( registers[index].address >= 0xf9 && registers[index].address <= 0xfe )
		{
			Delay( 3 );

			continue;
		}

		if ( ! RTL8188EU_WriteRF( control, registers[index].address, registers[index].value ) )
		{
			return ( FALSE );
		}
	}

	return ( TRUE );
}

