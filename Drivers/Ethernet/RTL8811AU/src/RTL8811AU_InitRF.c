static S32
WriteRFTable( struct USB2_EPResource *control, const struct RFRegister *table, U32 count )
{
	U32 index;

	for( index = 0; index < count; index++ )
	{
		if ( table[index].Address > 0xf8 )
		{
			Delay( ( table[index].Value + 19999U ) / 20000U );
		}
		else if ( ! RTL8811AU_WriteRF( control, table[index].Address, table[index].Value ) )
		{
			return ( FALSE );
		}
	}

	return ( TRUE );
}

// --

S32
RTL8811AU_InitRF( struct USB2_EPResource *control, const struct RTL8811AU_Board *board )
{
	const struct RFRegister *rf1;
	const struct RFRegister *rf2;
	const struct RFRegister *rf3;
	const struct RFRegister *rf4;

	U8 use_default;
	U8 external;

	use_default = ( board->BoardType == RTL8811AU_BOARD_DEFAULT ) || ( board->BoardType == RTL8811AU_BOARD_BT );
	external = board->BoardType == RTL8811AU_EXT_5GHZ;
	rf1 = use_default ? RF1Default : ( external ? RF1External : RF1 );
	rf2 = external ? RF2External : RF2;
	rf3 = use_default ? RF3Default : RF3;
	rf4 = use_default ? RF4Default : ( external ? RF4External : RF4 );

	return ( ( WriteRFTable( control, RF0, sizeof( RF0 ) / sizeof( RF0[0] ) ) ) &&
		( WriteRFTable( control, rf1, sizeof( RF1 ) / sizeof( RF1[0] ) ) ) &&
		( WriteRFTable( control, rf2, sizeof( RF2 ) / sizeof( RF2[0] ) ) ) &&
		( WriteRFTable( control, rf3, sizeof( RF3 ) / sizeof( RF3[0] ) ) ) &&
		( WriteRFTable( control, rf4, sizeof( RF4 ) / sizeof( RF4[0] ) ) ) &&
		( WriteRFTable( control, RF5, sizeof( RF5 ) / sizeof( RF5[0] ) ) ) );
}

