static S32
WriteAGC( struct USB2_EPResource *control, const U32 *values, U32 count )
{
	U32 index;

	for( index = 0; index < count; index++ )
	{
		if ( ! RTL8811AU_WriteReg( control, 0x081c, 4, values[index] ) )
		{
			return ( FALSE );
		}
	}

	return ( TRUE );
}

// --

S32
RTL8811AU_InitBaseband( struct USB2_EPResource *control, const struct RTL8811AU_Board *board )
{
	const U32 *agc;
	U32 index;
	U32 crystal;

	agc = board->BoardType == RTL8811AU_EXT_5GHZ ? AGC5GHzExternal : AGC5GHz;
	crystal = board->CrystalCap;

	if ( ( ! RTL8811AU_Update8( control, RTL8811AU_SYS_FUNC, 0, 0x07 ) ) ||
		( ! RTL8811AU_WriteReg( control, RTL8811AU_RF_CTRL, 1, 0x07 ) ) ||
		( ! RTL8811AU_WriteReg( control, 0x0076, 1, 0x07 ) ) )
	{
		return ( FALSE );
	}

	for( index = 0; index < sizeof( Registers ) / sizeof( Registers[0] ); index++ )
	{
		if ( ! RTL8811AU_WriteReg( control, Registers[index].Address, 4, Registers[index].Value ) )
		{
			return ( FALSE );
		}
	}

	return ( ( WriteAGC( control, AGC2GHz, sizeof( AGC2GHz ) / sizeof( AGC2GHz[0] ) ) ) &&
		( WriteAGC( control, agc, sizeof( AGC5GHz ) / sizeof( AGC5GHz[0] ) ) ) &&
		( WriteAGC( control, AGC5GHzEnd, sizeof( AGC5GHzEnd ) / sizeof( AGC5GHzEnd[0] ) ) ) &&
		( RTL8811AU_WriteReg( control, 0x0c50, 4, 0x22 ) ) &&
		( RTL8811AU_WriteReg( control, 0x0c50, 4, 0x20 ) ) &&
		( RTL8811AU_UpdateReg( control, 0x002c, 4, 0x00fff000, ( crystal | ( crystal << 6 ) ) << 12 ) ) );
}

