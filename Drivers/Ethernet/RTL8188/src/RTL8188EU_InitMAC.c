S32
RTL8188EU_InitMAC( struct USB2_EPResource *control )
{
	U32 index;

	for( index = 0; index < sizeof( registers ) / sizeof( registers[0] ); index++ )
	{
		if ( ! RTL8188EU_Write8( control, registers[index].address, registers[index].value ) )
		{
			return ( FALSE );
		}
	}

	return ( TRUE );
}

